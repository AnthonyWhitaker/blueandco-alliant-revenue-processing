// Generate src/api/schema.d.ts from ../openapi.json.
// Uses the openapi-typescript API (not the CLI) so binary fields — uploads and
// the XLSX export — are typed as Blob instead of string.
import { writeFileSync } from 'node:fs';

import openapiTS, { astToString } from 'openapi-typescript';
import ts from 'typescript';

const BLOB = ts.factory.createTypeReferenceNode(ts.factory.createIdentifier('Blob'));
const NULL = ts.factory.createLiteralTypeNode(ts.factory.createNull());

const ast = await openapiTS(new URL('../../openapi.json', import.meta.url), {
  // Fields with a server default stay optional in request bodies.
  defaultNonNullable: false,
  transform(schemaObject) {
    // OpenAPI 3.0 marks files as format: binary; 3.1 (FastAPI) uses contentMediaType.
    if (schemaObject.format === 'binary' || 'contentMediaType' in schemaObject) {
      return schemaObject.nullable ? ts.factory.createUnionTypeNode([BLOB, NULL]) : BLOB;
    }
    return undefined;
  },
});

const header =
  '/**\n * Generated by scripts/generate-api-types.mjs from openapi.json. Do not edit.\n */\n\n';
writeFileSync(new URL('../src/api/schema.d.ts', import.meta.url), header + astToString(ast));
